"""
Генератор логов для отладки (Автоматизация тестирования)
Генераторы отлично подходят для автоматической генерации логов, которые можно использовать при тестировании приложений и серверов.
Где использовать: Логирование приложений, тестирование серверов, мониторинг событий.
"""
import random
import time


# Функция-генератор, создающая случайные логи
def log_generator():
    levels = ["INFO", "WARNING", "ERROR", "DEBUG"]  # Возможные уровни логов
    messages = [
        "Соединение установлено",
        "Пользователь авторизован",
        "Ошибка подключения к серверу",
        "Запрос выполнен успешно",
        "Недостаточно прав для операции"
    ]

    while True:
        # Формируем строку лога с текущей датой и случайным уровнем ошибки
        yield f"{time.strftime('%Y-%m-%d %H:%M:%S')} [{random.choice(levels)}] {random.choice(messages)}"
        time.sleep(1)  # Делаем задержку, имитируя реальную запись логов


# Использование генератора
gen = log_generator()
for _ in range(5):  # Выведем 5 случайных логов
    print(next(gen))


"""
Генератор HTML-страниц (Создание статического контента)
Этот генератор позволяет автоматически создавать веб-страницы с разным содержимым, что удобно для тестирования шаблонов.
Где использовать: Генерация статических страниц, создание тестового контента для сайтов.
"""


# Функция-генератор для динамического создания HTML-страниц
def html_page_generator():
    titles = ["Главная", "О нас", "Контакты", "Блог", "Новости"]
    contents = [
        "Добро пожаловать на наш сайт!",
        "Мы занимаемся разработкой ПО.",
        "Свяжитесь с нами по email@example.com",
        "Последние обновления на нашем блоге.",
        "Свежие новости из мира технологий."
    ]

    while True:
        title = titles.pop(0)  # Берём первый заголовок и переносим его в конец списка
        titles.append(title)
        content = contents.pop(0)  # То же самое с текстами
        contents.append(content)

        # Генерируем HTML-код страницы
        yield f"<html><head><title>{title}</title></head><body><h1>{title}</h1><p>{content}</p></body></html>"


# Использование генератора
gen = html_page_generator()

# Записываем несколько сгенерированных страниц в файлы
with open("page1.html", "w", encoding="utf-8") as f:
    f.write(next(gen))

with open("page2.html", "w", encoding="utf-8") as f:
    f.write(next(gen))


"""
Генератор случайных пользователей (Заполнение базы данных, тестирование API)
Генератор помогает создавать случайные данные для тестирования API и базы данных.
Где использовать: Автоматическое заполнение базы данных, тестирование форм регистрации, генерация фейковых данных.
"""
import random


# Функция-генератор для создания случайных пользователей
def user_data_generator():
    names = ["Анна", "Иван", "Ольга", "Сергей", "Елена"]
    cities = ["Москва", "Санкт-Петербург", "Новосибирск", "Екатеринбург", "Казань"]

    while True:
        yield {
            "name": random.choice(names),  # Случайное имя
            "age": random.randint(18, 60),  # Возраст от 18 до 60 лет
            "city": random.choice(cities)  # Случайный город
        }


# Использование генератора
gen = user_data_generator()
for _ in range(3):  # Выведем 3 случайных пользователя
    print(next(gen))


"""
Генератор RSS-ленты для новостного сайта
Этот генератор поможет автоматически обновлять ленту новостей.
Где использовать: Создание RSS-лент для сайтов, автоматическая генерация контента. 
"""
import random
import time


# Функция-генератор для RSS-ленты
def rss_feed_generator():
    articles = [
        {"title": "Python 3.12 выпущен!", "link": "https://example.com/python312"},
        {"title": "Новый фреймворк для веба", "link": "https://example.com/web-framework"},
        {"title": "Как оптимизировать код", "link": "https://example.com/code-optimization"}
    ]

    while True:
        article = random.choice(articles)  # Выбираем случайную статью
        yield f"<item><title>{article['title']}</title><link>{article['link']}</link><pubDate>{time.strftime('%Y-%m-%d %H:%M:%S')}</pubDate></item>"
        time.sleep(2)  # Имитация обновления новостей


# Использование генератора
gen = rss_feed_generator()
for _ in range(2):  # Выведем 2 новости
    print(next(gen))
